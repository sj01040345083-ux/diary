// ── 마이너 아르카나 만들기 도우미 ──
// 각 슈트는 에이스~10, 그리고 시종·기사·여왕·왕(코트 카드)로 이루어집니다.
type MinorSeed = {
  rank: string // 에이스, 2 … 10, 시종, 기사, 여왕, 왕
  emoji: string
  keywords: [string, string, string]
  upright: string
  reversed: string
}

function makeSuit(suit: Suit, seeds: MinorSeed[]): TarotCard[] {
  const s = suitInfo[suit]
  return seeds.map((seed, i) => ({
    id: `${suit}-${i + 1}`,
    name: `${s.name} ${seed.rank}`,
    nameEn: `${seed.rank} of ${suit}`,
    arcana: 'minor' as const,
    suit,
    emoji: seed.emoji,
    keywords: seed.keywords,
    upright: seed.upright,
    reversed: seed.reversed,
  }))
}

